function translatedValue(source, language) {
  const leading = source.match(/^\s*/)?.[0] || "";
  const trailing = source.match(/\s*$/)?.[0] || "";
  const core = source.trim();
  if (!core) return source;
  return `${leading}${translateDynamic(core, language)}${trailing}`;
}

function localizeTextNode(node, language) {
  const current = node.nodeValue || "";
  const prior = textOrigins.get(node);
  const source = !prior || current !== prior.output ? current : prior.source;
  const output = translatedValue(source, language);
  textOrigins.set(node, { source, output });
  if (current !== output) node.nodeValue = output;
}

function localizeElementAttributes(element, language) {
  let records = attributeOrigins.get(element);
  if (!records) {
    records = new Map();
    attributeOrigins.set(element, records);
  }
  for (const attribute of TRANSLATABLE_ATTRIBUTES) {
    if (!element.hasAttribute(attribute)) continue;
    const current = element.getAttribute(attribute) || "";
    const prior = records.get(attribute);
    const source = !prior || current !== prior.output ? current : prior.source;
    const output = translateDynamic(source, language);
    records.set(attribute, { source, output });
    if (current !== output) element.setAttribute(attribute, output);
  }
  if (element instanceof HTMLTextAreaElement) {
    const current = element.value;
    const prior = records.get("__value");
    const source = !prior || current !== prior.output ? current : prior.source;
    const output = translateDynamic(source, language);
    records.set("__value", { source, output });
    if (current !== output) element.value = output;
  }
}

export function localizeDocument(root, language) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node = walker.currentNode;
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) {
      const parent = node.parentElement;
      if (parent && !["SCRIPT", "STYLE", "CODE"].includes(parent.tagName)) localizeTextNode(node, language);
    } else if (node instanceof Element) {
      localizeElementAttributes(node, language);
    }
    node = walker.nextNode();
  }
}

export function observeLocalizedDocument(root, language) {
  if (!root) return () => {};
  let frame = 0;
  const observer = new MutationObserver(() => {
    cancelAnimationFrame(frame);
    frame = requestAnimationFrame(apply);
  });
  const watch = () => observer.observe(root, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: TRANSLATABLE_ATTRIBUTES,
  });
  function apply() {
    observer.disconnect();
    localizeDocument(root, language);
    watch();
  }
  apply();
  return () => {
    cancelAnimationFrame(frame);
    observer.disconnect();
  };
}

